#!/usr/bin/env bun
import { execFileSync, spawn } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { basename, join, relative } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const DS_DIR = join(ROOT, 'design-systems')
const LIB_DIR = join(ROOT, '..', 'lib')
// Published design systems live at the repo root, beside the lib.
const ROOT_DS = [join(ROOT, '..', 'ui')]
const SWITCHER = join(ROOT, 'components', 'demo-switcher')
const PEERS_FILE = join(ROOT, 'components', 'demo-switcher', '.peers.json')
const TEMP_CONFIG = '.modo.config.ts'
const SITE_DIR = join(ROOT, 'dist')
const LANDING_DIR = join(ROOT, 'landing')
const BRAND_DIR = join(ROOT, '..', '.github', 'brand')
// Scrapers want an absolute og:image, and the site's own origin isn't known here.
const OG_IMAGE = 'https://raw.githubusercontent.com/justAnArthur/modo/main/.github/brand/og.png'
const BASE_PORT = 5173
// By path, not `bunx modo`: before the lib is built its bin has nothing to
// run, and bunx then fetches the unrelated `modo` from npm. Node runs Vite
// directly, so a signal reaches it instead of a wrapper.
const MODO_CLI = join(LIB_DIR, 'dist', 'cli.js')
// The path the built site is served under, e.g. `/modo/` on a GitHub Pages project site.
const SITE_BASE = process.env.SITE_BASE ?? '/'

const build = process.argv.includes('--build')
const wanted = process.argv.slice(2).filter(a => a !== '--build')
// Dir husks can outlive their tracked files (a merge-deleted DS leaves .modo-tmp/ behind).
const dirs = new Map(
  [...readdirSync(DS_DIR).map(name => join(DS_DIR, name)), ...ROOT_DS]
    .filter(dir => existsSync(join(dir, 'modo.config.ts')))
    .map(dir => [basename(dir), dir]),
)
const all = [...dirs.keys()].sort()
const targets = wanted.length > 0 ? all.filter(n => wanted.includes(n)) : all
if (targets.length === 0) {
  process.stderr.write(`no design systems found${wanted.length > 0 ? ` matching: ${wanted.join(', ')}` : ''}\n`)
  process.stderr.write('usage: bun scripts/run-design-systems.ts [--build] [name ...]\n')
  process.exit(1)
}

// The temp config re-exports the real one with the switcher appended, so a
// design system that ships its own panel items (ui's theme switcher) keeps
// them instead of having `panel` overwritten. With one design system there is
// nothing to switch to, and the panel would show an empty "Switcher" section.
function withSwitcher(dir: string) {
  if (targets.length < 2)
    return "// generated by scripts/run-design-systems.ts — safe to delete\nexport { default } from './modo.config'\n"
  const item = JSON.stringify({ label: 'Switcher', component: relative(dir, SWITCHER) })
  return [
    '// generated by scripts/run-design-systems.ts — safe to delete',
    "import base from './modo.config'",
    '',
    'export default {',
    '  ...base,',
    `  panel: { items: [...(base.panel?.items ?? []), ${item}] },`,
    '}',
    '',
  ].join('\n')
}
const dirOf = (name: string) => dirs.get(name)!

function removeTemp(names: string[]) {
  for (const name of names) rmSync(join(dirOf(name), TEMP_CONFIG), { force: true })
  rmSync(PEERS_FILE, { force: true })
}

// Rebuilt when any lib source is newer: a stale CLI runs old flags silently (an old one ignored --out).
function cliIsStale() {
  if (!existsSync(MODO_CLI)) return true
  const built = statSync(MODO_CLI).mtimeMs
  const src = join(LIB_DIR, 'src')
  return readdirSync(src, { recursive: true, encoding: 'utf8' }).some(rel => statSync(join(src, rel)).mtimeMs > built)
}
if (cliIsStale()) execFileSync('bun', ['run', 'build'], { cwd: LIB_DIR, stdio: 'inherit' })
// A previous run killed hard leaves its temp configs behind.
removeTemp(all)
const peerUrl = (name: string, i: number) => (build ? `${SITE_BASE}${name}/` : `http://localhost:${BASE_PORT + i}/`)
writeFileSync(
  PEERS_FILE,
  JSON.stringify(
    targets.map((name, i) => ({ name, url: peerUrl(name, i) })),
    null,
    2,
  ),
)
for (const name of targets) writeFileSync(join(dirOf(name), TEMP_CONFIG), withSwitcher(dirOf(name)))

async function buildSite() {
  rmSync(SITE_DIR, { recursive: true, force: true })
  mkdirSync(SITE_DIR)
  for (const name of targets) {
    // --out: a published design system's own dist/ holds its package build.
    const args = ['build', '--config', TEMP_CONFIG, '--base', `${SITE_BASE}${name}/`, '--out', join(SITE_DIR, name)]
    execFileSync('node', [MODO_CLI, ...args], { cwd: dirOf(name), stdio: 'inherit' })
  }
  writeFileSync(join(SITE_DIR, 'index.html'), await landing())
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const read = (path: string) => readFileSync(path, 'utf8')

async function card(name: string) {
  const dir = dirOf(name)
  const config = (await import(join(dir, 'modo.config.ts'))).default
  const description = config.description ?? JSON.parse(read(join(dir, 'package.json'))).description ?? ''
  const href = `${SITE_BASE}${name}/`
  return `<a class="card" href="${esc(href)}"><div class="card-title">${esc(config.name ?? name)}<span aria-hidden="true">→</span></div><p>${esc(description)}</p><code>${esc(href)}</code></a>`
}

// The template links its colors so it previews on its own; the build inlines them.
const COLORS_LINK = '<link rel="stylesheet" href="./tokens/colors.css" />'

// Self-contained: the brand assets are inlined, so the page works under any SITE_BASE.
async function landing() {
  const fills: Record<string, string> = {
    base: esc(SITE_BASE),
    description: esc(
      'modo reads the tokens, primitives, components, blocks and pages of a design system and renders its docs site, with chrome built from its own components.',
    ),
    logo: read(join(BRAND_DIR, 'logo.svg')).trim(),
    favicon: `data:image/svg+xml,${encodeURIComponent(read(join(BRAND_DIR, 'favicon.svg')).trim())}`,
    og: OG_IMAGE,
    cards: (await Promise.all(targets.map(card))).join(''),
  }
  return read(join(LANDING_DIR, 'index.html'))
    .replace(COLORS_LINK, `<style>\n${read(join(LANDING_DIR, 'tokens', 'colors.css'))}</style>`)
    .replace(/\{\{(\w+)\}\}/g, (_, key: string) => fills[key]!)
}

// Each server takes its port strictly, so a stale one from another run fails
// loudly instead of being silently replaced.
function serve() {
  const children = targets.map((name, i) =>
    spawn('node', [MODO_CLI, 'dev', '--config', TEMP_CONFIG], {
      cwd: dirOf(name),
      stdio: 'inherit',
      env: { ...process.env, MODO_PORT: String(BASE_PORT + i) },
    }),
  )
  const cleanup = () => {
    for (const child of children) child.kill('SIGTERM')
    removeTemp(targets)
    process.exit(0)
  }
  for (const signal of ['SIGINT', 'SIGTERM', 'SIGHUP'] as const) process.on(signal, cleanup)
}

if (build) {
  try {
    await buildSite()
  } finally {
    removeTemp(targets)
  }
} else {
  serve()
}
